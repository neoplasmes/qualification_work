import type {
    Action,
    ActionDefinitionPayload,
    ActionEffect,
    ActionParameter,
} from '@/core/entities/action';

import type { ActionBuilderDraft, ActionValueMappingDraft } from './actionBuilderDraft';
import { createActionBuilderDraftId } from './actionBuilderIds';
import {
    actionBuilderValuesToMap,
    parseActionBuilderDraftValue,
    parseActionBuilderLiteralValue,
    valueToActionBuilderDraftString,
} from './actionBuilderValues';

export type ActionBuilderOutput = {
    payload: ActionDefinitionPayload | null;
    error: string;
    canSave: boolean;
};

const valuesMapToDraft = (values: ActionEffect['values']): ActionValueMappingDraft[] =>
    Object.entries(values).map(([columnKey, source]) => ({
        id: createActionBuilderDraftId(),
        columnKey,
        sourceKind: source.kind,
        parameterKey: source.kind === 'parameter' ? source.key : '',
        literalValue:
            source.kind === 'literal'
                ? valueToActionBuilderDraftString(source.value)
                : '',
        operation: source.kind === 'computed' ? '=' : (source.operation ?? '='),
        leftParameterKey: source.kind === 'computed' ? source.leftParameterKey : '',
        computedOperation: source.kind === 'computed' ? source.operation : '*',
        rightParameterKey: source.kind === 'computed' ? source.rightParameterKey : '',
    }));

const getMatchSourceKind = (effect: ActionEffect) => {
    if (effect.kind !== 'updateRowsByMatch') {
        return 'parameter';
    }

    return effect.match.source?.kind ?? 'parameter';
};

export const actionToBuilderDraft = (action: Action): ActionBuilderDraft => ({
    id: action.id,
    name: action.name,
    description: action.description ?? null,
    parameters: action.parameters.map(parameter => ({
        id: createActionBuilderDraftId(),
        key: parameter.key,
        label: parameter.label,
        type: parameter.type,
        required: parameter.required ?? false,
        defaultValue: valueToActionBuilderDraftString(parameter.defaultValue),
        hidden: parameter.hidden ?? false,
        keyAutoGenerated: false,
    })),
    effects: action.effects.map(effect => ({
        id: createActionBuilderDraftId(),
        kind: effect.kind,
        datasetId: effect.datasetId,
        matchColumnKey: effect.kind === 'updateRowsByMatch' ? effect.match.columnKey : '',
        matchSourceKind: getMatchSourceKind(effect),
        matchParameterKey:
            effect.kind === 'updateRowsByMatch'
                ? effect.match.source?.kind === 'parameter'
                    ? effect.match.source.key
                    : (effect.match.parameterKey ?? '')
                : '',
        matchLiteralValue:
            effect.kind === 'updateRowsByMatch' && effect.match.source?.kind === 'literal'
                ? valueToActionBuilderDraftString(effect.match.source.value)
                : '',
        maxRows: effect.kind === 'updateRowsByMatch' ? String(effect.maxRows ?? 1) : '1',
        values: valuesMapToDraft(effect.values),
    })),
});

export const builderDraftToActionPayload = (
    draft: ActionBuilderDraft
): ActionDefinitionPayload => {
    const name = draft.name.trim();
    if (!name) {
        throw new Error('Укажите название действия.');
    }

    const parameters = getPayloadParameters(draft);
    const parameterKeys = new Set(parameters.map(parameter => parameter.key));
    if (parameterKeys.size !== parameters.length) {
        throw new Error('Ключи параметров должны быть уникальными.');
    }

    const effects = getPayloadEffects(draft, parameterKeys);
    if (effects.length === 0) {
        throw new Error('Добавьте хотя бы один эффект.');
    }

    return {
        name,
        description: draft.description,
        parameters,
        effects,
    };
};

export const createActionBuilderOutput = (
    draft: ActionBuilderDraft
): ActionBuilderOutput => {
    try {
        return {
            payload: builderDraftToActionPayload(draft),
            error: '',
            canSave: true,
        };
    } catch (error) {
        return {
            payload: null,
            error:
                error instanceof Error ? error.message : 'Не удалось сохранить действие.',
            canSave: false,
        };
    }
};

const getPayloadParameters = (draft: ActionBuilderDraft): ActionParameter[] =>
    draft.parameters
        .filter(parameter => parameter.key.trim() || parameter.label.trim())
        .map(parameter => {
            const key = parameter.key.trim();
            const label = parameter.label.trim();
            if (!key || !label) {
                throw new Error('Укажите ключ и название каждого параметра.');
            }

            const nextParameter: ActionParameter = {
                key,
                label,
                type: parameter.type,
                required: parameter.required,
            };
            if (parameter.hidden) {
                nextParameter.hidden = true;
            }
            const defaultValue = parseActionBuilderDraftValue(
                parameter.type,
                parameter.defaultValue
            );
            if (defaultValue !== undefined) {
                nextParameter.defaultValue = defaultValue;
            }

            return nextParameter;
        });

const getPayloadEffects = (
    draft: ActionBuilderDraft,
    parameterKeys: Set<string>
): ActionEffect[] =>
    draft.effects.map<ActionEffect>((effect, index) => {
        const datasetId = effect.datasetId.trim();
        const values = actionBuilderValuesToMap(effect.values, effect.kind);
        if (!datasetId) {
            throw new Error(`Эффект ${index + 1}: выберите таблицу.`);
        }
        if (Object.keys(values).length === 0) {
            throw new Error(`Эффект ${index + 1}: укажите хотя бы одно значение поля.`);
        }
        assertValueSourcesKnown(values, parameterKeys, index);

        if (effect.kind === 'insertRow') {
            return { kind: 'insertRow', datasetId, values };
        }

        return getUpdateRowsEffect(effect, index, datasetId, values, parameterKeys);
    });

const getUpdateRowsEffect = (
    effect: ActionBuilderDraft['effects'][number],
    index: number,
    datasetId: string,
    values: ActionEffect['values'],
    parameterKeys: Set<string>
): ActionEffect => {
    if (!effect.matchColumnKey) {
        throw new Error(`Эффект ${index + 1}: выберите поле для поиска.`);
    }

    if (effect.matchSourceKind === 'parameter') {
        if (!effect.matchParameterKey || !parameterKeys.has(effect.matchParameterKey)) {
            throw new Error(`Эффект ${index + 1}: неизвестный параметр поиска.`);
        }
    }

    const maxRows = Number(effect.maxRows || 1);
    if (!Number.isInteger(maxRows) || maxRows < 1) {
        throw new Error(
            `Эффект ${index + 1}: максимальное число строк должно быть целым и положительным.`
        );
    }

    return {
        kind: 'updateRowsByMatch',
        datasetId,
        match: {
            columnKey: effect.matchColumnKey,
            source:
                effect.matchSourceKind === 'literal'
                    ? {
                          kind: 'literal',
                          value: parseActionBuilderLiteralValue(effect.matchLiteralValue),
                      }
                    : {
                          kind: 'parameter',
                          key: effect.matchParameterKey,
                      },
        },
        values,
        maxRows,
    };
};

const assertValueSourcesKnown = (
    values: ActionEffect['values'],
    parameterKeys: Set<string>,
    index: number
) => {
    for (const source of Object.values(values)) {
        if (source.kind === 'parameter') {
            if (!source.key || !parameterKeys.has(source.key)) {
                throw new Error(`Эффект ${index + 1}: неизвестный параметр значения.`);
            }
        } else if (
            source.kind === 'computed' &&
            (!parameterKeys.has(source.leftParameterKey) ||
                !parameterKeys.has(source.rightParameterKey))
        ) {
            throw new Error(`Эффект ${index + 1}: неизвестный параметр вычисления.`);
        }
    }
};
