import type { ConfigBind } from '@/features/Config';

import type {
    ActionBuilderDraft,
    ActionEffectDraft,
    ActionParameterDraft,
    ActionValueMappingDraft,
} from './actionBuilderDraft';
import { labelToActionBuilderKey } from './actionBuilderValues';

export const createParameterFieldBind = <K extends keyof ActionParameterDraft>(
    parameterId: string,
    field: K
): ConfigBind<ActionBuilderDraft, ActionParameterDraft[K]> => ({
    get: draft =>
        draft.parameters.find(parameter => parameter.id === parameterId)?.[
            field
        ] as ActionParameterDraft[K],
    set: (draft, value) => {
        const parameter = draft.parameters.find(item => item.id === parameterId);

        if (!parameter) {
            return;
        }

        parameter[field] = value;

        if (field === 'label' && parameter.keyAutoGenerated) {
            parameter.key = labelToActionBuilderKey(String(value ?? ''));
        }

        if (field === 'key') {
            parameter.keyAutoGenerated = false;
        }
    },
});

export const createEffectFieldBind = <K extends keyof ActionEffectDraft>(
    effectId: string,
    field: K
): ConfigBind<ActionBuilderDraft, ActionEffectDraft[K]> => ({
    get: draft =>
        draft.effects.find(effect => effect.id === effectId)?.[
            field
        ] as ActionEffectDraft[K],
    set: (draft, value) => {
        const effect = draft.effects.find(item => item.id === effectId);

        if (effect) {
            effect[field] = value;
        }
    },
});

export const createMappingFieldBind = <K extends keyof ActionValueMappingDraft>(
    effectId: string,
    mappingId: string,
    field: K
): ConfigBind<ActionBuilderDraft, ActionValueMappingDraft[K]> => ({
    get: draft =>
        draft.effects
            .find(effect => effect.id === effectId)
            ?.values.find(mapping => mapping.id === mappingId)?.[
            field
        ] as ActionValueMappingDraft[K],
    set: (draft, value) => {
        const effect = draft.effects.find(item => item.id === effectId);
        const mapping = effect?.values.find(item => item.id === mappingId);

        if (mapping) {
            mapping[field] = value;
        }
    },
});
